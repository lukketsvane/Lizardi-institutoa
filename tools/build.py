#!/usr/bin/env python3
"""Generate the four pages, the web-app manifest and the service worker.

    python3 tools/build.py

Reads content.json (order, titles, alt text) and assets/meta.json (image sizes,
written by tools/images.py). No dependencies.
"""
import hashlib
import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = json.loads((ROOT / "content.json").read_text())
M = json.loads((ROOT / "assets" / "meta.json").read_text())
SITE, BOOK, DIARY, ABOUT, SPRITES = C["site"], C["book"], C["diary"], C["about"], C["sprites"]
OCHRE, GARDEN, GRAPE, PAPER = "#c48c33", "#9da94a", "#5d157f", "#f5f1f8"  # book cover, shelf, diary ink and paper, as in assets/site.css
SPLASH = M.get("splash", [])  # launch screens for iPhones, written by tools/images.py

ICON = {  # 24x24, drawn with a stroke
    "down": '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 9l7 7 7-7"/></svg>',
    "prev": '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M15 5l-7 7 7 7"/></svg>',
    "next": '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M9 5l7 7-7 7"/></svg>',
    "chapters": '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 5h5v5H5zM14 5h5v5h-5zM5 14h5v5H5zM14 14h5v5h-5z"/></svg>',
}

# Pages are fetched fresh when online and fall back to the saved copy offline.
# Everything else is served from the saved copy, and saved the first time it is seen.
SERVICE_WORKER = """// Generated by tools/build.py; edit the template there.
const CACHE = "lizardi-VERSION";
const SHELL = FILES;

self.addEventListener("install", event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", event => {
  const stale = key => key.startsWith("lizardi-") && key !== CACHE;
  event.waitUntil(
    caches.keys().then(keys => Promise.all(keys.filter(stale).map(key => caches.delete(key)))).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const saved = await cache.match(request);
    if (saved && request.mode !== "navigate") return saved;
    try {
      const fresh = await fetch(request);
      if (fresh.status === 200) cache.put(request, fresh.clone());
      return fresh;
    } catch (error) {
      if (saved) return saved;
      throw error;
    }
  })());
});
"""


def e(s):
    return escape(s, quote=True)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def version():
    """Changes whenever anything that is served changes. Names the offline cache
    and is appended to the CSS and JS addresses, so nobody is left with old files."""
    h = hashlib.sha256(Path(__file__).read_bytes() + (ROOT / "content.json").read_bytes())
    for path in sorted((ROOT / "assets").rglob("*")):
        if path.is_file():
            h.update(f"{path.relative_to(ROOT).as_posix()}:{path.stat().st_size}".encode())
            if path.suffix in (".css", ".js", ".json"):
                h.update(path.read_bytes())
    return h.hexdigest()[:10]


V = version()


def head(title, description, root, theme):
    og = (SITE["url"].rstrip("/") + "/" if SITE["url"] else root) + "assets/og.jpg"
    # While an installed app starts, iOS shows the picture made for exactly that screen, or else a white flash.
    launch = "\n".join(
        f'<link rel="apple-touch-startup-image" href="{root}assets/splash/{w}x{h}-{r}x.png" media="(device-width: {w}px) and '
        f'(device-height: {h}px) and (-webkit-device-pixel-ratio: {r}) and (orientation: portrait)">'
        for w, h, r in SPLASH
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<title>{e(title)}</title>
<meta name="description" content="{e(description)}">
<meta name="theme-color" content="{theme}">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="{e(SITE["short_name"])}">
<link rel="manifest" href="{root}manifest.webmanifest">
<link rel="icon" href="{root}favicon.ico" sizes="48x48">
<link rel="icon" type="image/png" sizes="192x192" href="{root}assets/icons/icon-192.png">
<link rel="apple-touch-icon" href="{root}assets/icons/apple-touch-icon.png">
{launch}
<meta property="og:type" content="website">
<meta property="og:title" content="{e(title)}">
<meta property="og:description" content="{e(description)}">
<meta property="og:image" content="{og}">
<meta name="twitter:card" content="summary_large_image">
<link rel="stylesheet" href="{root}assets/site.css?v={V}">
<script>
if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("{root}sw.js"));
addEventListener("gesturestart", event => event.preventDefault()); // no pinch-zoom in Safari: it is an app
addEventListener("touchstart", () => {{}}, {{passive: true}}); // lets iOS show the pressed look of things
</script>
</head>
"""


def preview(m):
    """The tiny inline preview shows through until the real image has loaded."""
    return f'style="background:url({m["lq"]}) 0 0/100% 100%"'


def page_picture(page, root, sizes, eager=False, alt=None):
    m = M["diary"][page["id"]]
    base = f"{root}assets/diary/{page['id']}"
    load = 'fetchpriority="high"' if eager else 'loading="lazy"'
    return (
        f'<picture><source type="image/avif" srcset="{base}-800.avif 800w, {base}-1200.avif 1200w, {base}-1600.avif 1600w" sizes="{sizes}">'
        f'<img src="{base}-1000.webp" width="1000" height="{round(1000 * m["h"] / m["w"])}" '
        f'alt="{e(page["alt"] if alt is None else alt)}" {load} decoding="async" {preview(m)}></picture>'
    )


def wall(root, cover, stir=""):
    """The background collage; assets/wall.js scatters the drawings and moves them with the scrolling
    (or, with stir, with a swipe, where the page itself does not scroll)."""
    tilting = ("bug", "poop", "lizard", "microbe")  # these may lie at any angle; plants and animals stay upright
    sprites = [[name, M["sprites"][name]["w"], M["sprites"][name]["h"], int(kind in tilting)] for name, kind in SPRITES.items()]
    return (f'<div class="wall" aria-hidden="true" {stir} data-src="{root}assets/sprites/" data-cover="{cover}" '
            f"data-sprites='{json.dumps(sprites, separators=(',', ':'))}'></div>")


def face(person, root, alt, size=""):
    m = M["faces"][person["id"]]
    return f'<img src="{root}assets/faces/{person["id"]}{size}.webp" width="{m["w"]}" height="{m["h"]}" alt="{e(alt)}" decoding="async">'


def spread_alt(s):
    return " ".join(f"{side} page: {s[key]}" for side, key in (("Left", "left"), ("Right", "right")) if s[key])


# ---------------------------------------------------------------- the shelf

def home():
    cover = BOOK["spreads"][0]["id"]
    m = M["book"][cover]
    first_page = {p["id"]: p for ch in DIARY["chapters"] for p in ch["pages"]}[DIARY["cover"]]
    faces = "".join(f'<a href="about/#{p["id"]}">{face(p, "", p["name"], "-200")}</a>' for p in ABOUT["people"])
    return head(SITE["name"], SITE["description"], "", GARDEN) + f"""<body class="home">
<h1 class="vh">{e(SITE["name"])}</h1>
{wall("", 0.9, "data-stir")}
<main class="shelf">
<a class="work book" href="book/" aria-label="{e(BOOK["title"])}"><img src="assets/book/{cover}-1280.webp" width="1280" height="{round(1280 * m["h"] / m["w"])}" alt="" fetchpriority="high"></a>
<a class="work diary" href="diary/" aria-label="{e(DIARY["title"])}">{page_picture(first_page, "", "(max-aspect-ratio: 1/1) 60vw, 31vw", eager=True, alt="")}</a>
<nav class="faces" aria-label="{e(ABOUT["title"])}">{faces}</nav>
</main>
<script type="module" src="assets/wall.js?v={V}"></script>
</body>
</html>
"""


# ---------------------------------------------------------------- the picture book

def book():
    spreads = BOOK["spreads"]
    first = M["book"][spreads[0]["id"]]
    out = []
    for i, s in enumerate(spreads, 1):
        m = M["book"][s["id"]]
        base = f"../assets/book/{s['id']}"
        load = 'fetchpriority="high"' if i == 1 else 'loading="lazy"'
        out.append(
            f'<div class="spread" id="{i}" style="--l:{m["l"]};--r:{m["r"]}">'
            f'<img src="{base}-1280.webp" srcset="{base}-1280.webp 1280w, {base}-2400.webp 2400w" sizes="(max-aspect-ratio: 1/1) 200vw, min(100vw, 142vh)" '
            f'width="{m["w"]}" height="{m["h"]}" alt="{e(spread_alt(s))}" {load} decoding="async" {preview(m)}><i></i><i></i></div>'
        )
    return head(f'{BOOK["title"]} · {SITE["name"]}', BOOK["description"], "../", first["r"]) + f"""<body class="reader">
<h1 class="vh">{e(BOOK["title"])}</h1>
<main class="pages" tabindex="0" aria-label="{len(spreads)} spreads" style="--ar:{first["w"] / first["h"]:.4f}">
{chr(10).join(out)}
</main>
<i class="tint"></i>
<nav class="chrome" aria-label="Controls">
<a class="ic back" href="../" aria-label="Close">{ICON["down"]}</a>
<button class="ic prev" type="button" aria-label="Previous page" disabled>{ICON["prev"]}</button>
<span class="progress" aria-hidden="true"><i></i></span>
<button class="ic next" type="button" aria-label="Next page">{ICON["next"]}</button>
<span class="count vh" aria-live="polite"></span>
</nav>
<noscript><style>.pages{{scrollbar-width:auto}}.prev,.next,.progress{{display:none}}</style></noscript>
<script type="module" src="../assets/book.js?v={V}"></script>
</body>
</html>
"""


# ---------------------------------------------------------------- the diary

def diary():
    sizes = "(min-width: 760px) 760px, 100vw"
    sections, thumbs = [], []
    for ci, ch in enumerate(DIARY["chapters"]):
        cid, title, first = slug(ch["title"]), e(ch["title"]), ch["pages"][0]["id"]
        figures = "".join(
            f'<figure class="page" id="{p["id"]}">{page_picture(p, "../", sizes, eager=(ci == 0 and pi == 0))}</figure>'
            for pi, p in enumerate(ch["pages"])
        )
        sections.append(f'<section class="chapter" id="{cid}" aria-labelledby="{cid}-h"><h2 class="vh" id="{cid}-h">{title}</h2>{figures}</section>')
        m = M["diary"][first]
        thumbs.append(
            f'<li><a href="#{cid}" title="{title}"><img src="../assets/diary/{first}-240.webp" width="240" height="{round(240 * m["h"] / m["w"])}" '
            f'alt="{title}" loading="lazy" decoding="async"></a></li>'
        )
    return head(f'{DIARY["title"]} · {SITE["name"]}', DIARY["description"], "../", GRAPE) + f"""<body class="diary">
<h1 class="vh">{e(DIARY["title"])}</h1>
{wall("../", 0.6)}
<nav class="bar" aria-label="Controls">
<a class="ic back" href="../" aria-label="Back">{ICON["prev"]}</a>
<button class="ic grid" type="button" aria-label="Chapters" aria-haspopup="dialog">{ICON["chapters"]}</button>
<span class="progress" aria-hidden="true"><i></i></span>
</nav>
<main class="strip">
{chr(10).join(sections)}
</main>
<dialog class="sheet" aria-label="Chapters">
<div class="grab"></div>
<ol class="thumbs">{"".join(thumbs)}</ol>
</dialog>
<noscript><style>.grid,.progress{{display:none}}</style></noscript>
<script type="module" src="../assets/wall.js?v={V}"></script>
<script type="module" src="../assets/diary.js?v={V}"></script>
</body>
</html>
"""


# ---------------------------------------------------------------- the people

def about():
    people = "\n".join(
        f'<section class="person" id="{p["id"]}">{face(p, "../", "")}<h2>{e(p["name"])}</h2><p class="role">{e(p["role"])}</p>'
        + "".join(f"<p>{e(par)}</p>" for par in p["text"].split("\n\n") if par) + "</section>"
        for p in ABOUT["people"]
    )
    return head(f'{ABOUT["title"]} · {SITE["name"]}', SITE["description"], "../", PAPER) + f"""<body class="about">
<h1 class="vh">{e(ABOUT["title"])}</h1>
<a class="ic back" href="../" aria-label="Back">{ICON["prev"]}</a>
<main class="people">
{people}
</main>
</body>
</html>
"""


# ---------------------------------------------------------------- the app wrapper

def manifest():
    icon = lambda name, size, **more: {"src": f"assets/icons/{name}.png", "sizes": f"{size}x{size}", "type": "image/png", **more}
    return json.dumps({
        "name": SITE["name"],
        "short_name": SITE["short_name"],
        "description": SITE["description"],
        "start_url": "./",
        "scope": "./",
        "display": "standalone",
        "background_color": GARDEN,
        "theme_color": GARDEN,
        "icons": [icon("icon-192", 192), icon("icon-512", 512), icon("icon-maskable-512", 512, purpose="maskable")],
    }, indent=1) + "\n"


def service_worker():
    shell = ["./", "book/", "diary/", "about/", "manifest.webmanifest", "assets/icons/icon-192.png",
             *(f"assets/{name}?v={V}" for name in ("site.css", "wall.js", "book.js", "diary.js"))]
    return SERVICE_WORKER.replace("VERSION", V).replace("FILES", json.dumps(shell))


def main():
    outputs = {"index.html": home(), "book/index.html": book(), "diary/index.html": diary(), "about/index.html": about(),
               "manifest.webmanifest": manifest(), "sw.js": service_worker()}
    for path, text in outputs.items():
        out = ROOT / path
        out.parent.mkdir(exist_ok=True)
        out.write_text(text)
        print(path, f"{len(text) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
